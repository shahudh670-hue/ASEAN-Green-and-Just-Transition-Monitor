import { useState } from 'react';
import type { Insight, InsightKind } from '../lib/insights';
import { openIndicator, useApp } from '../lib/context';
import { countryName } from '../lib/data';
import { SourceLine, refOf, type SourceRef } from './ChartCard';

const KIND: Record<InsightKind, { label: string; icon: string; colour: string }> = {
  progress: { label: 'Progress', icon: '▲', colour: 'var(--good)' },
  risk: { label: 'Risk', icon: '!', colour: 'var(--risk)' },
  gap: { label: 'Gap', icon: '◐', colour: 'var(--brand)' },
  finance: { label: 'Finance', icon: '$', colour: 'var(--brand)' },
  note: { label: 'Note', icon: 'i', colour: 'var(--ink-2)' },
};

function insightSources(ds: ReturnType<typeof useApp>['ds'], ins: Insight): SourceRef[] {
  const refs: SourceRef[] = ins.indicators.map((id) => ds.catalogue.find((m) => m.id === id)).filter((m): m is NonNullable<typeof m> => Boolean(m)).map(refOf);
  if (ins.id === 'energy-poverty') refs.push({ label: '2026 global MPI, Table 1', name: 'UNDP and OPHI, 2026 Global Multidimensional Poverty Index', url: ds.static.mpi.sourceUrl });
  if (ins.id === 'graduation') refs.push({ label: 'Income group, FY2027', name: 'World Bank country and lending groups', url: ds.static.income.sourceUrl });
  if (ins.id === 'decoupling' || ins.id === 'access-gap') refs.push(refOf(ds.catalogue.find((m) => m.id === (ins.id === 'decoupling' ? 'aux_gdp' : 'aux_pop'))!));
  return refs;
}

export function InsightCard({ ins, compact = false }: { ins: Insight; compact?: boolean }) {
  const c = useApp();
  const [open, setOpen] = useState(false);
  const k = KIND[ins.kind];
  const pillar = c.ds.meta.pillars.find((p) => p.id === ins.pillar);
  return (
    <article className="card flex flex-col gap-2 p-4">
      <div className="flex items-center gap-2 text-xs font-semibold">
        <span className="inline-flex items-center gap-1 rounded-full border px-2 py-0.5" style={{ color: k.colour, borderColor: k.colour }}>
          <span aria-hidden>{k.icon}</span>
          {k.label}
        </span>
        {pillar && <span className="text-ink-3">{pillar.short}</span>}
      </div>
      <h4 className="text-[16px] font-semibold leading-snug text-ink">{ins.title}</h4>
      <p className={`text-[15px] leading-relaxed text-ink-2 ${compact && !open ? 'line-clamp-4' : ''}`}>{ins.body}</p>
      {open && ins.evidence.length > 0 && (
        <dl className="tabular mt-1 grid grid-cols-1 gap-x-4 gap-y-1 rounded-lg border border-line bg-raised p-3 text-sm">
          {ins.evidence.map((e, i) => (
            <div key={i} className="flex flex-wrap justify-between gap-x-3">
              <dt className="text-ink-2">{e.label}</dt>
              <dd className="font-semibold text-ink">{e.value}</dd>
            </div>
          ))}
        </dl>
      )}
      <SourceLine refs={insightSources(c.ds, ins)} />
      <div className="mt-auto flex flex-wrap gap-2 pt-1">
        <button className="btn btn-primary" onClick={() => openIndicator(c, ins.focus.indicator, ins.focus.countries, ins.focus.view, ins.focus.x, ins.focus.y)}>
          Show the evidence
        </button>
        {ins.evidence.length > 0 && (
          <button className="btn" aria-expanded={open} onClick={() => setOpen((o) => !o)}>
            {open ? 'Hide numbers' : 'Numbers used'}
          </button>
        )}
      </div>
    </article>
  );
}

export function PillarInsights() {
  const c = useApp();
  const list = c.insights.filter((i) => i.pillar === c.state.pillar);
  if (!list.length) return null;
  return (
    <section aria-label="Automated policy insights for this pillar">
      <div className="mb-2 flex items-baseline justify-between gap-2">
        <h3 className="text-[17px] font-semibold text-ink">What the data say</h3>
        <button className="text-sm font-semibold text-brand hover:underline" onClick={() => c.set({ tab: 'insights' })}>
          All {c.insights.length} insights
        </button>
      </div>
      <div className="grid grid-cols-1 gap-3 lg:grid-cols-2 2xl:grid-cols-3">
        {list.map((i) => (
          <InsightCard key={i.id} ins={i} compact />
        ))}
      </div>
    </section>
  );
}

export default function InsightsView() {
  const c = useApp();
  const [pillar, setPillar] = useState<string>('all');
  const [country, setCountry] = useState<string>('all');
  const [kind, setKind] = useState<string>('all');
  const list = c.insights.filter(
    (i) => (pillar === 'all' || i.pillar === pillar) && (country === 'all' || i.countries.includes(country)) && (kind === 'all' || i.kind === kind),
  );
  return (
    <div className="space-y-4">
      <div className="card p-4">
        <h2 className="text-[20px] font-bold text-ink">Automated policy insights</h2>
        <p className="mt-1 max-w-3xl text-[15px] text-ink-2">
          Each statement is generated by a fixed rule from the latest published data, and is rewritten automatically when the data are refreshed. Open
          "Numbers used" to see every figure behind a statement, or "Show the evidence" to jump to the chart. The rules describe patterns; they do not
          establish causes.
        </p>
        <div className="mt-3 flex flex-wrap gap-3">
          <label className="flex flex-col gap-1">
            <span className="eyebrow">Pillar</span>
            <select className="select" value={pillar} onChange={(e) => setPillar(e.target.value)}>
              <option value="all">All pillars</option>
              {c.ds.meta.pillars.map((p) => (
                <option key={p.id} value={p.id}>
                  {p.label}
                </option>
              ))}
            </select>
          </label>
          <label className="flex flex-col gap-1">
            <span className="eyebrow">Country</span>
            <select className="select" value={country} onChange={(e) => setCountry(e.target.value)}>
              <option value="all">All members</option>
              {c.ds.meta.countries.map((ct) => (
                <option key={ct.iso3} value={ct.iso3}>
                  {ct.name}
                </option>
              ))}
            </select>
          </label>
          <label className="flex flex-col gap-1">
            <span className="eyebrow">Type</span>
            <select className="select" value={kind} onChange={(e) => setKind(e.target.value)}>
              <option value="all">All types</option>
              {Object.entries(KIND).map(([k, v]) => (
                <option key={k} value={k}>
                  {v.label}
                </option>
              ))}
            </select>
          </label>
        </div>
      </div>
      {list.length === 0 ? (
        <p className="text-ink-2">No insight matches these filters{country !== 'all' ? ` for ${countryName(c.ds, country)}` : ''}.</p>
      ) : (
        <div className="grid grid-cols-1 gap-3 lg:grid-cols-2 2xl:grid-cols-3">
          {list.map((i) => (
            <InsightCard key={i.id} ins={i} />
          ))}
        </div>
      )}
    </div>
  );
}
